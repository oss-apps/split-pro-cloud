const CATEGORY_LABELS: Record<string, string> = {
  general: 'General',
  ...Object.fromEntries(
    Object.entries(CATEGORIES).flatMap(([categoryName, categoryDetails]) => [
      [categoryName, categoryDetails.name],
      ...categoryDetails.items.flatMap((item) =>
        Object.entries(item).filter(([key]) => 'other' !== key),
      ),
    ]),
  ),
};

/** The name shown for a stored category, e.g. "diningOut" is "Dining Out". */
export const getCategoryLabel = (category: string) => CATEGORY_LABELS[category] ?? category;
